const { chromium } = require('playwright');
(async () => {
  const [url, out] = process.argv.slice(2);
  const browser = await chromium.launch(), errs = [], fails = [];
  const page = await browser.newPage({ viewport: { width: 960, height: 600 } });
  page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
  page.on('pageerror', (e) => errs.push(e.message));
  const key = async (k, wait = 200) => { await page.keyboard.press(k); await page.waitForTimeout(wait); };
  const check = (what, ok) => { console.log((ok ? 'ok    ' : 'FAIL  ') + what); if (!ok) fails.push(what); };
  const ws = (fn, arg) => page.evaluate(fn, arg);
  await page.goto(url); await page.waitForTimeout(800);
  await key('Enter'); await key('ArrowRight'); await key('Enter'); // START -> VS (second) -> players
  await page.screenshot({ path: `${out}/spec-menu.png` });
  await key('ArrowDown'); await page.screenshot({ path: `${out}/spec-menu-foc.png` });
  await key('Enter'); await page.screenshot({ path: `${out}/spec-tracks.png` });
  await key('Enter'); await page.waitForTimeout(6000);
  check('a spectated race has eight computer worms', await ws(() => { const r = window.__ws.race; return r && r.worms.length === 8 && r.worms.every((w) => !w.human) && window.__ws.G.players.length === 1 && window.__ws.G.players[0].spectator; }));
  await page.screenshot({ path: `${out}/spec-race.png` });
  const row = await ws(() => { const h = window.__ws.G.players[0].hud, n = h.layer.n, r = h.rows[5]; return { idx: r[0], x: (r[1] + 10) * n, y: (r[2] + r[4] / 2) * n, ax: (h.autoBox[0] + 5) * n, ay: (h.autoBox[1] + 4) * n }; });
  await page.mouse.click(row.x, row.y); await page.waitForTimeout(600);
  check('clicking a name watches that worm and turns auto off', await ws((i) => { const p = window.__ws.G.players[0]; return p.me === i && !p.auto; }, row.idx));
  await page.screenshot({ path: `${out}/spec-picked.png` });
  await page.mouse.click(row.ax, row.ay); await page.waitForTimeout(300);
  check('the button turns auto back on', await ws(() => window.__ws.G.players[0].auto));
  // An item picked up shows beside the worm's name for a moment.
  await ws(() => { const r = window.__ws.race, w = r.worms.find((o) => !o.out && !o.finished); window.__ws.give(w.idx, 15); });
  await page.waitForTimeout(500); await page.screenshot({ path: `${out}/spec-item.png` });
  check('the list notes the item', await ws(() => { const g = window.__ws.G.players[0].hud.got || {}; return Object.values(g).some((x) => x.t > 0 && x.item === 15); }));
  await ws(() => window.__ws.event('brand', 3)); await page.waitForTimeout(1500);
  check('auto view cuts to the worm the hand visits', await ws(() => window.__ws.G.players[0].me === 3));
  await page.screenshot({ path: `${out}/spec-event.png` });
  // An event that comes by itself: the view should already be on its worm when it starts, and the list should point at it.
  await page.waitForFunction(() => window.__ws.race.weather.type === 'none', null, { timeout: 20000 });
  await ws(() => { const x = window.__ws.race.weather; x.on = true; x.may = ['check']; x.omen = null; x.next = 2.5; });
  await page.waitForFunction(() => window.__ws.race.weather.omen, null, { timeout: 8000 });
  await page.waitForTimeout(250);
  const early = await ws(() => { const x = window.__ws.race.weather; return { type: x.type, want: x.omen && x.omen.idx, me: window.__ws.G.players[0].me }; });
  check('auto view is on the worm before its event starts', early.type === 'none' && early.me === early.want);
  await page.waitForFunction(() => window.__ws.race.weather.type === 'check', null, { timeout: 8000 });
  check('the event comes for the worm that was foreseen', await ws((i) => window.__ws.race.weather.visit === i, early.want));
  await page.waitForTimeout(1600); await page.screenshot({ path: `${out}/spec-marked.png` });
  await page.waitForFunction(() => window.__ws.race.weather.type === 'none', null, { timeout: 20000 });
  await page.screenshot({ path: `${out}/spec-framed.png` });
  await ws(() => { const x = window.__ws.race.weather; x.may = ['bird']; x.omen = null; x.next = 1.6; });
  await page.waitForFunction(() => window.__ws.race.worms.some((w) => w.out), null, { timeout: 30000 });
  await page.waitForTimeout(600);
  check('the view stays with a worm as the bird eats it, at the nest', await ws(() => { const p = window.__ws.G.players[0]; return window.__ws.race.worms[p.me].out && !!window.__ws.nest; }));
  await page.screenshot({ path: `${out}/spec-nest.png` });
  await ws(() => { window.__ws.race.weather.on = false; window.__ws.race.weather.next = Infinity; });
  const t0 = Date.now();
  await page.waitForFunction(() => !window.__ws.race.worms[window.__ws.G.players[0].me].out, null, { timeout: 15000 });
  check('it stays at the nest long enough to see the worm fed to the chicks', Date.now() - t0 > 5000);
  check('then it goes back to the race', true);
  const back = await page.waitForFunction(() => window.__ws.race.worms[window.__ws.G.players[0].me].out, null, { timeout: 45000 }).then(() => true, () => false);
  check('and looks in on the eaten worm again later', back);
  await key('ArrowRight');
  check('left and right step through the worms', await ws(() => !window.__ws.G.players[0].auto));
  await ws(() => { const r = window.__ws.race; for (let n = 0; r.state !== 'done' && n < 90000; n++) r.step(1 / 60); });
  await page.waitForTimeout(2500); await page.screenshot({ path: `${out}/spec-results.png` });
  check('the race ends by itself with a score screen', (await page.locator('.panel table').innerText()).length > 20);
  check('no event is waiting once everyone has finished', await ws(() => { const r = window.__ws.race, x = r.weather; x.on = true; x.may = ['rain']; x.type = 'none'; x.next = 0.5; for (let n = 0; n < 300; n++) r.step(1 / 60); return x.type === 'none'; }));
  console.log('errors:', errs.length ? errs : 'none');
  await browser.close(); process.exit(fails.length || errs.length ? 1 : 0);
})();
